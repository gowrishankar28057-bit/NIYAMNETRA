import io
from datetime import timedelta

from reportlab.lib.colors import HexColor
from reportlab.lib.pagesizes import A4
from reportlab.pdfgen import canvas

from . import catalog
from .analysis import active_documents

IST = timedelta(hours=5, minutes=30)


def _ist(dt):
    return (dt + IST).strftime("%d %b %Y, %I:%M %p IST") if dt else "—"


def acknowledgement_pdf(app):
    buf = io.BytesIO()
    c = canvas.Canvas(buf, pagesize=A4)
    w, h = A4
    c.setTitle(f"Acknowledgement {app.application_number}")
    c.setFillColor(HexColor("#0b2a5b"))
    c.rect(0, h - 90, w, 90, fill=1, stroke=0)
    c.setFillColor(HexColor("#ffffff"))
    c.setFont("Helvetica-Bold", 18)
    c.drawString(40, h - 45, "NeyamNetra — Application Acknowledgement")
    c.setFont("Helvetica", 9)
    c.drawString(40, h - 64, "DEMONSTRATION ACKNOWLEDGEMENT • SIH 2026 PROTOTYPE • NOT AN OFFICIAL AICTE DOCUMENT")
    docs = active_documents(app)
    rows = [
        ("Application ID", app.application_number),
        ("Institution", app.institution.name),
        ("Institution ID", app.institution.permanent_id),
        ("Application Type", catalog.APP_TYPE_SHORT[app.app_type]),
        ("Academic Year", app.academic_year.replace("-", " – ")),
        ("Submitted", _ist(app.submitted_at)),
        ("Current Status", catalog.STATUS_LABELS[app.status]),
        ("Documents", str(len(docs))),
        ("Checklist Template", app.handbook_version),
    ]
    y = h - 130
    c.setFillColor(HexColor("#111827"))
    for label, value in rows:
        c.setFont("Helvetica-Bold", 10.5)
        c.drawString(48, y, label)
        c.setFont("Helvetica", 10.5)
        c.drawString(200, y, str(value)[:80])
        y -= 20
    y -= 10
    c.setFont("Helvetica-Bold", 11)
    c.drawString(48, y, "Documents submitted")
    y -= 18
    c.setFont("Helvetica", 9.5)
    for d in docs:
        c.drawString(56, y, f"• {d.original_filename[:60]}  ({d.requirement_code}, {d.size_bytes // 1024} KB, readability: {d.status.replace('_', ' ')})")
        y -= 15
        if y < 90:
            c.showPage()
            y = h - 60
            c.setFont("Helvetica", 9.5)
    c.setFont("Helvetica-Oblique", 8.5)
    c.setFillColor(HexColor("#6b7280"))
    c.drawString(40, 50, "Generated by the NeyamNetra prototype from stored application records. Readability checks do not establish authenticity.")
    c.drawString(40, 38, "SIH 2026 Prototype • NeyamNetra by Neural Nexus • Not an official AICTE service")
    c.showPage()
    c.save()
    return buf.getvalue()
